"""Route parsing and orientation helpers, checked without a ROS environment."""

import math

import pytest

from control.algorithms.geometry import yaw_from_quaternion
from control.algorithms.route import (RouteError, load_route_csv, parse_route,
                                      route_length_m)

GOOD = ["x_m,y_m,speed_mps", "0.0,0.0,5.0", "1.0,0.0,5.0", "2.0,0.0,4.0"]


# ----------------------------------------------------------------- parsing

def test_a_well_formed_route_parses_in_order():
    route = parse_route(GOOD)
    assert [sample.x_m for sample in route] == [0.0, 1.0, 2.0]
    assert route[-1].speed_mps == 4.0


def test_blank_lines_and_comments_are_ignored():
    route = parse_route(["# generated by the planner", "", *GOOD, "  "])
    assert len(route) == 3


def test_the_header_must_say_what_the_columns_are():
    with pytest.raises(RouteError, match="expected header"):
        parse_route(["x,y,v", "0,0,1", "1,0,1"])


def test_a_header_alone_is_not_a_route():
    with pytest.raises(RouteError, match="at least two samples"):
        parse_route(["x_m,y_m,speed_mps"])


def test_one_sample_is_not_a_route():
    """The tracker needs a segment, and a single point does not make one."""
    with pytest.raises(RouteError, match="at least two samples"):
        parse_route(["x_m,y_m,speed_mps", "0,0,1"])


def test_the_wrong_number_of_fields_names_the_line():
    with pytest.raises(RouteError, match="line 3"):
        parse_route(["x_m,y_m,speed_mps", "0,0,1", "1,0"])


def test_non_numeric_data_names_the_line():
    with pytest.raises(RouteError, match="line 2"):
        parse_route(["x_m,y_m,speed_mps", "zero,0,1", "1,0,1"])


@pytest.mark.parametrize("bad", ["nan", "inf", "-inf"])
def test_non_finite_values_are_refused(bad):
    with pytest.raises(RouteError, match="not finite"):
        parse_route(["x_m,y_m,speed_mps", f"{bad},0,1", "1,0,1"])


def test_negative_speed_is_refused_where_the_line_number_is_known():
    """Reverse along a route is unspecified; fail at parse, not mid-lap."""
    with pytest.raises(RouteError, match="line 3"):
        parse_route(["x_m,y_m,speed_mps", "0,0,1", "1,0,-1"])


def test_zero_speed_is_allowed():
    """A planned stop is a speed of zero, which is a decision, not an error."""
    assert parse_route(["x_m,y_m,speed_mps", "0,0,0", "1,0,0"])[0].speed_mps == 0.0


def test_whitespace_around_fields_is_tolerated():
    route = parse_route(["x_m , y_m , speed_mps", " 0.0 , 0.0 , 5.0 ", "1,0,5"])
    assert route[0].x_m == 0.0


# ----------------------------------------------------------------- files

def test_loading_from_a_file_round_trips(tmp_path):
    path = tmp_path / "route.csv"
    path.write_text("\n".join(GOOD), encoding="utf-8")
    assert len(load_route_csv(path)) == 3


def test_a_missing_file_is_a_route_error_naming_the_path(tmp_path):
    missing = tmp_path / "absent.csv"
    with pytest.raises(RouteError, match="absent.csv"):
        load_route_csv(missing)


def test_a_malformed_file_reports_its_own_path(tmp_path):
    path = tmp_path / "broken.csv"
    path.write_text("nope\n", encoding="utf-8")
    with pytest.raises(RouteError, match="broken.csv"):
        load_route_csv(path)


# ----------------------------------------------------------------- length

def test_route_length_sums_the_segments():
    assert route_length_m(parse_route(GOOD)) == pytest.approx(2.0)


def test_route_length_is_not_wrapped_closed():
    """An open polyline; closing it would invent a segment the planner omitted."""
    square = parse_route(["x_m,y_m,speed_mps", "0,0,1", "1,0,1", "1,1,1", "0,1,1"])
    assert route_length_m(square) == pytest.approx(3.0)


# ----------------------------------------------------------------- yaw

@pytest.mark.parametrize("angle", [0.0, 0.5, -0.5, math.pi / 2, -math.pi / 2, 3.0, -3.0])
def test_yaw_round_trips_through_a_planar_quaternion(angle):
    q = (0.0, 0.0, math.sin(angle / 2.0), math.cos(angle / 2.0))
    assert yaw_from_quaternion(*q) == pytest.approx(angle)


def test_yaw_normalises_an_unnormalised_quaternion():
    """Estimators drift off the unit sphere; the heading is still recoverable."""
    angle = 0.7
    scale = 3.0
    q = (0.0, 0.0, scale * math.sin(angle / 2.0), scale * math.cos(angle / 2.0))
    assert yaw_from_quaternion(*q) == pytest.approx(angle)


def test_yaw_ignores_roll_and_pitch_rather_than_failing():
    """A tilted kart still has a heading, and the planar tracker needs only that."""
    roll = 0.2
    yaw = 1.1
    # Composition of a roll and a yaw, as a quaternion.
    cr, sr = math.cos(roll / 2.0), math.sin(roll / 2.0)
    cy, sy = math.cos(yaw / 2.0), math.sin(yaw / 2.0)
    q = (sr * cy, sr * sy, cr * sy, cr * cy)
    assert yaw_from_quaternion(*q) == pytest.approx(yaw, abs=1e-9)


def test_a_zero_quaternion_is_refused_rather_than_answered():
    with pytest.raises(ValueError):
        yaw_from_quaternion(0.0, 0.0, 0.0, 0.0)


def test_a_non_finite_quaternion_is_refused():
    with pytest.raises(ValueError):
        yaw_from_quaternion(0.0, 0.0, float("nan"), 1.0)
